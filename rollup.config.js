import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import commonjs from '@rollup/plugin-commonjs'
import json from '@rollup/plugin-json'

const require = createRequire(import.meta.url)
const { version } = require('nearley/package.json')
const license = readFileSync(require.resolve('nearley/LICENSE.txt'), 'utf-8')

export default [
  {
    // Vendor the nearley runtime so it is not a runtime dependency.
    input: require.resolve('nearley'),
    output: {
      file: 'src/nearley.js',
      format: 'es',
      banner: `// nearley ${version} runtime https://github.com/kach/nearley
// Generated by rollup.config.js. Do not edit.
/*
${license.trim()}
*/`
    },
    context: 'globalThis',
    plugins: [
      commonjs()
    ]
  },
  {
    input: 'index.js',
    output: {
      file: 'dist/index.cjs',
      format: 'cjs',
      exports: 'named'
    },
    plugins: [
      json(),
      commonjs()
    ],
    external: [
      'randexp'
    ]
  }
]
